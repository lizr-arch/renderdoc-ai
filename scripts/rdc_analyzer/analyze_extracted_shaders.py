def parse_result(result: MaliAnalysisResult) -> dict:
    """Parse MaliAnalysisResult into report dict"""
    if not result.success:
        return {'error': result.error_message}
    
    return {
        'cycles': result.cycles,
        'bottleneck': result.bottleneck,
        'work_registers': result.work_registers,
        'uniform_registers': result.uniform_registers,
        'has_fp16': 'Yes' if result.has_fp16 else 'No',
    }


def main():
    parser = argparse.ArgumentParser(description='Analyze extracted shaders with Mali Offline Compiler')
    parser.add_argument('--input', '-i', 
                        default=r'd:\Code\git\renderdoc\scripts\rdc_analyzer\extracted_shaders',
                        help='Input directory with extracted shaders')
    parser.add_argument('--output', '-o',
                        default=r'd:\Code\git\renderdoc\scripts\rdc_analyzer\mali_report.html',
                        help='Output HTML report path')
    parser.add_argument('--gpu', '-g', default='Mali-G78',
                        help='Target GPU (default: Mali-G78)')
    parser.add_argument('--malioc', '-m',
                        default=r'D:\Program Files\Arm\Arm Performance Studio 2025.3\mali_offline_compiler\malioc.exe',
                        help='Path to malioc.exe')
    
    args = parser.parse_args()
    
    # Check input
    manifest_path = os.path.join(args.input, 'manifest.json')
    if not os.path.exists(manifest_path):
        print(f"[ERROR] Manifest not found: {manifest_path}")
        print("[INFO] Please run extract_shaders.py in RenderDoc first.")
        return 1
    
    # Check malioc
    if not os.path.exists(args.malioc):
        print(f"[ERROR] Mali Offline Compiler not found: {args.malioc}")
        return 1
    
    # Initialize compiler
    compiler = MaliCompiler(malioc_path=args.malioc, default_gpu=args.gpu)
    
    if not compiler.is_available():
        print("[ERROR] Mali Offline Compiler not available")
        return 1
    
    print(f"[INFO] Mali Offline Compiler: {compiler.get_version()}")
    print(f"[INFO] Target GPU: {args.gpu}")
    
    # Load manifest
    with open(manifest_path, 'r', encoding='utf-8') as f:
        manifest = json.load(f)
    
    print(f"[INFO] Found {manifest['extracted']} shader sets in manifest")
    
    # Analyze each shader
    results = []
    
    for shader_info in manifest.get('shaders', []):
        event_id = shader_info['eventId']
        
        # Analyze vertex shader
        if 'vertex_shader' in shader_info:
            vs_path = os.path.join(args.input, shader_info['vertex_shader'])
            if os.path.exists(vs_path):
                print(f"[ANALYZE] {shader_info['vertex_shader']}...")
                result = compiler.analyze_file(vs_path, shader_type='vertex')
                results.append({
                    'file': shader_info['vertex_shader'],
                    'event_id': event_id,
                    'shader_type': 'Vertex',
                    **parse_result(result)
                })
        
        # Analyze fragment shader
        if 'fragment_shader' in shader_info:
            ps_path = os.path.join(args.input, shader_info['fragment_shader'])
            if os.path.exists(ps_path):
                print(f"[ANALYZE] {shader_info['fragment_shader']}...")
                result = compiler.analyze_file(ps_path, shader_type='fragment')
                results.append({
                    'file': shader_info['fragment_shader'],
                    'event_id': event_id,
                    'shader_type': 'Fragment',
                    **parse_result(result)
                })
    
    # Generate report
    if results:
        report_path = generate_html_report(results, args.output, args.gpu)
        print(f"\n[DONE] Report generated: {report_path}")
        print(f"[INFO] Analyzed {len(results)} shaders")
    else:
        print("[WARN] No shaders analyzed")
    
    return 0


if __name__ == '__main__':
    sys.exit(main())