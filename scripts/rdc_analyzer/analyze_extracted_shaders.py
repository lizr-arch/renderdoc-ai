"""
Standalone Mali Offline Compiler Analysis Script

This script analyzes extracted shaders from RenderDoc using Mali Offline Compiler.
It reads the manifest.json generated by extract_shaders.py and produces a HTML report.

Usage:
    py -3 analyze_extracted_shaders.py [--gpu Mali-G78]
"""

import os
import sys
import json
import argparse
import subprocess
import tempfile
from dataclasses import dataclass, field
from typing import Dict, Optional, List, Any


@dataclass
class MaliAnalysisResult:
    """Analysis result from Mali Offline Compiler"""
    success: bool = False
    error_message: str = ""
    cycles: Dict[str, float] = field(default_factory=dict)
    bottleneck: str = ""
    work_registers: int = 0
    uniform_registers: int = 0
    has_fp16: bool = False
    raw_json: Dict[str, Any] = field(default_factory=dict)


class MaliCompiler:
    """Wrapper for Mali Offline Compiler (malioc)"""
    
    def __init__(self, malioc_path: str, default_gpu: str = "Mali-G78"):
        self.malioc_path = malioc_path
        self.default_gpu = default_gpu
        self._version = None
    
    def is_available(self) -> bool:
        """Check if malioc is available"""
        return os.path.exists(self.malioc_path)
    
    def get_version(self) -> str:
        """Get malioc version"""
        if self._version:
            return self._version
        try:
            result = subprocess.run(
                [self.malioc_path, "--version"],
                capture_output=True, text=True, timeout=10
            )
            self._version = result.stdout.strip().split('\n')[0]
            return self._version
        except Exception:
            return "Unknown"
    
    def analyze_file(self, shader_path: str, shader_type: str = "fragment",
                     gpu: str = None) -> MaliAnalysisResult:
        """Analyze a shader file"""
        gpu = gpu or self.default_gpu
        
        # Map shader type to malioc option (use full --option names)
        stage_map = {
            'vertex': '--vertex',
            'fragment': '--fragment',
            'compute': '--compute',
            'vert': '--vertex',
            'frag': '--fragment',
        }
        stage_opt = stage_map.get(shader_type.lower(), '--fragment')
        
        try:
            result = subprocess.run(
                [
                    self.malioc_path,
                    "--format", "json",
                    "--core", gpu,
                    stage_opt,
                    shader_path
                ],
                capture_output=True, text=True, timeout=60
            )
            
            if result.returncode != 0:
                return MaliAnalysisResult(
                    success=False,
                    error_message=result.stderr or result.stdout
                )
            
            # Parse JSON output
            data = json.loads(result.stdout)
            return self._parse_json_output(data)
            
        except json.JSONDecodeError as e:
            return MaliAnalysisResult(success=False, error_message=f"JSON parse error: {e}")
        except subprocess.TimeoutExpired:
            return MaliAnalysisResult(success=False, error_message="Timeout")
        except Exception as e:
            return MaliAnalysisResult(success=False, error_message=str(e))
    
    def _parse_json_output(self, data: Dict[str, Any]) -> MaliAnalysisResult:
        """Parse malioc JSON output (Schema v2)"""
        result = MaliAnalysisResult(success=True, raw_json=data)
        
        try:
            # Get first shader result
            shaders = data.get("shaders", [])
            if not shaders:
                result.success = False
                result.error_message = "No shader data in output"
                return result
            
            shader = shaders[0]
            variants = shader.get("variants", [])
            if not variants:
                result.success = False
                result.error_message = "No variants in shader"
                return result
            
            variant = variants[0]
            
            # Parse properties (list format in v2)
            props = variant.get("properties", [])
            props_dict = {}
            for p in props:
                if isinstance(p, dict) and "name" in p and "value" in p:
                    props_dict[p["name"]] = p["value"]
            
            # Use the correct property names from malioc JSON schema v2
            result.work_registers = int(props_dict.get("work_registers_used", 0))
            result.uniform_registers = int(props_dict.get("uniform_registers_used", 0))
            # fp16_arithmetic is a numeric percentage (0-100), not a string
            fp16_val = props_dict.get("fp16_arithmetic", 0)
            result.has_fp16 = fp16_val > 0 if isinstance(fp16_val, (int, float)) else False
            
            # Parse performance cycles
            perf = variant.get("performance", {})
            pipelines = perf.get("pipelines", [])
            cycle_data = perf.get("shortest_path_cycles", {})
            cycle_counts = cycle_data.get("cycle_count", [])
            
            # Map pipeline names to cycle values by index
            bound_map = {
                "arith_total": "A", "arith_fma": "A", "arithmetic": "A",
                "load_store": "LS", "texture": "T", "varying": "V",
            }
            
            cycles = {}
            max_cycles = 0.0
            bottleneck = "A"
            
            for i, name in enumerate(pipelines):
                if i < len(cycle_counts):
                    val = cycle_counts[i]
                    unit = bound_map.get(name.lower(), name[0].upper())
                    cycles[unit] = val
                    if val > max_cycles:
                        max_cycles = val
                        bottleneck = unit
            
            result.cycles = cycles
            result.bottleneck = bottleneck
            
        except Exception as e:
            result.success = False
            result.error_message = f"Parse error: {e}"
        
        return result


